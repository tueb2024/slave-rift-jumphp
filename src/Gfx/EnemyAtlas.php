    public static function frame(string $type, string $state, int $tick, int $direction): ?array
    {
        $sheet = self::SHEETS[$type] ?? self::SHEETS['guardian'];
        if ($state === 'death') {
            $frames = $sheet['frames'][$sheet['death']];
            return $frames[min(count($frames)-1, max(0, $tick))] ?? null;
        }
        $clip = $sheet['clips'][$state] ?? $sheet['clips']['walk'];
        $row = $clip[$tick % count($clip)];
        return $sheet['frames'][$row][$direction % 8] ?? null;
    }

    public static function valid(array $sheet, array $rect): bool
    {
        return $rect[0] >= 0 && $rect[1] >= 0 && $rect[2] > 0 && $rect[3] > 0
            && $rect[0] + $rect[2] <= $sheet['width']
            && $rect[1] + $rect[3] <= $sheet['height'];
    }
